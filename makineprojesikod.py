# GÖREV 3: VERİ BÖLME VE DOĞRU NORMALİZASYON (KUSURSUZ MİMARİ - STRATIFY HATASI DÜZELTİLDİ)
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler

# 1. Ana veriden tertemiz X ve y alıyoruz
X_ham = df_temiz.drop(columns=['label']).reset_index(drop=True)
y_ham = df_temiz['label'].reset_index(drop=True)

# 2. İLK BÖLÜNME: %70 Train, %30 Geçici (Temp)
# Burada stratify olarak y_ham kullanıyoruz
X_train_raw, X_temp_raw, y_train, y_temp = train_test_split(
    X_ham, y_ham, test_size=0.30, random_state=42, stratify=y_ham
)

# 3. İKİNCİ BÖLÜNME: %30'luk Geçici seti yarı yarıya bölüyoruz (%15 Val, %15 Test)
# KRİTİK DÜZELTME: stratify parametresine artık 'y_temp' vermeliyiz, en baştaki 'y_ham'ı değil!
X_val_raw, X_test_raw, y_val, y_test = train_test_split(
    X_temp_raw, y_temp, test_size=0.50, random_state=42, stratify=y_temp
)

# 4. AKADEMİK OLARAK DOĞRU ÖLÇEKLENDİRME (DATA LEAKAGE ENGELLENDİ)
scaler = MinMaxScaler()

# Sadece Train setiyle fit_transform yapıyoruz
X_train = scaler.fit_transform(X_train_raw)

# Val ve Test setlerini sadece transform ediyoruz (Sızıntı bitti!)
X_val = scaler.transform(X_val_raw)
X_test = scaler.transform(X_test_raw)

print("Veri bölme ve güvenli normalizasyon başarıyla tamamlandı! 🎉")
print("Eğitim (Train) seti boyutu       :", X_train.shape[0])
print("Doğrulama (Validation) seti boyutu:", X_val.shape[0])
print("Test seti boyutu                 :", X_test.shape[0])

#GÖREV 3

# 1. Model: Random Forest (Rastgele Orman)
