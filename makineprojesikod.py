# Grafikleme fonksiyonu (Aynı anda iki seti de çizecek şekilde güncelledik)
def c_matris_ikili_ciz(y_val_true, y_val_pred, y_test_true, y_test_pred, model_adi):
    fig, ax = plt.subplots(1, 2, figsize=(16, 6))

    # Doğrulama Seti Matrisi
    cm_val = confusion_matrix(y_val_true, y_val_pred)
    disp_val = ConfusionMatrixDisplay(confusion_matrix=cm_val)
    disp_val.plot(cmap='Greens', ax=ax[0])
    ax[0].set_title(f"{model_adi} - Doğrulama Seti")

    # Test Seti Matrisi
    cm_test = confusion_matrix(y_test_true, y_test_pred)
    disp_test = ConfusionMatrixDisplay(confusion_matrix=cm_test)
    disp_test.plot(cmap='Blues', ax=ax[1])
    ax[1].set_title(f"{model_adi} - Test Seti")

    plt.suptitle(f"--- {model_adi} Karışıklık Matrisleri ---", fontsize=16, y=1.02)
    plt.show()

# 3 Model için de grafikleri ekrana basalım
c_matris_ikili_ikili_ciz = c_matris_ikili_ciz # Kısa isim referansı
c_matris_ikili_ciz(y_val, rf_pred_val, y_test, rf_pred_test, "Random Forest")
c_matris_ikili_ciz(y_val, svm_pred_val, y_test, svm_pred_test, "SVM")
c_matris_ikili_ciz(y_val, nb_pred_val, y_test, nb_pred_test, "Naive Bayes")

"""📝 Görev 3: Modelleme (Güncellenmiş Özet Notlar)
Veri Bölme: Veri seti, modelin ezberlemesini (overfitting) kesin olarak önlemek ve hiperparametre optimizasyonunu güvenli bir şekilde gerçekleştirmek amacıyla modern veri bilimi standartlarına uygun olarak %70 Eğitim (Train), %15 Doğrulama (Validation) ve %15 Test seti olacak şekilde 3'e ayrılmıştır. stratify parametresi kullanılarak tüm alt setlerdeki 20 farklı bitki sınıfının dengeli dağılımı korunmuştur.

Algoritma Seçimi: Proje isterlerine tam uyum sağlayacak şekilde, farklı matematiksel altyapılara sahip 3 güçlü makine öğrenmesi modeli seçilmiştir: Random Forest (Topluluk Öğrenme), SVM (Geometrik/Vektör Tabanlı Sınıflandırma) ve Naive Bayes (Olasılık Tabanlı Sınıflandırma).

Model Eğitimi: Modeller; toprak (N, P, K, pH) ve iklim (Sıcaklık, Nem, Yağış) değişkenlerini girdi olarak alıp, "Yatırım Danışmanlığı" senaryomuz altındaki en optimize bitki türünü (label) tahmin etmek üzere eğitilmiştir.

Performans Ölçümü ve Doğrulama: Modellerin gerçek dünya verilerindeki başarısını simüle etmek amacıyla, performans analizi hem hiperparametre kararlarının alındığı Doğrulama (Validation) seti üzerinde hem de modelin daha önce kesinlikle karşılaşmadığı nihai Test seti üzerinde ayrı ayrı yürütülmüştür.

Çift Yönlü Karışıklık Matrisi (Confusion Matrix) Analizi: Modellerin sınıf bazındaki başarılarını ve birbirine yakın iklim/toprak istekleri olan mahsulleri (örneğin mısır ve pirinç) ne oranda karıştırdığını gözlemlemek adına, hem Doğrulama hem de Test setleri için ikili karışıklık matrisleri çizdirilerek karşılaştırmalı analiz yapılmıştır.
"""

# GÖREV 4: MODEL DEĞERLENDİRME METRİKLERİ
from sklearn.metrics import accuracy_score, classification_report

def metrikleri_yazdir_v3(model, X_train, y_train, X_val, y_val, X_test, y_test, model_adi):
    # Tüm setler için tahminlerin üretilmesi
    train_pred = model.predict(X_train)
    val_pred = model.predict(X_val)
    test_pred = model.predict(X_test)

    print(f"\n==================== {model_adi} Performans Sonuçları ====================")
    # Hocanın istediği 3'lü Accuracy listesi
    print(f"Eğitim Doğruluğu (Train Accuracy)      : {accuracy_score(y_train, train_pred):.4f}")
    print(f"Doğrulama Doğruluğu (Val Accuracy)     : {accuracy_score(y_val, val_pred):.4f}")
    print(f"Test Doğruluğu (Test Accuracy)         : {accuracy_score(y_test, test_pred):.4f}")

    # 1. Eğitim Seti Detaylı Raporu
    print(f"\n[Eğitim (Train) Seti Detaylı Raporu]:")
    print(classification_report(y_train, train_pred))

    # 2. Detaylı raporlar (Precision, Recall, F1-Score)
    print(f"\n[Doğrulama (Validation) Seti Detaylı Raporu]:")
    print(classification_report(y_val, val_pred))

    # 3. Nihai Test Seti Detaylı Raporu
    print(f"\n[Nihai Test Seti Detaylı Raporu]:")
    print(classification_report(y_test, test_pred))

# 3 Modeli de yeni 3'lü sistemimizle test edelim
metrikleri_yazdir_v3(rf_model, X_train, y_train, X_val, y_val, X_test, y_test, "Random Forest")
metrikleri_yazdir_v3(svm_model, X_train, y_train, X_val, y_val, X_test, y_test, "Support Vector Machine")
metrikleri_yazdir_v3(nb_model, X_train, y_train, X_val, y_val, X_test, y_test, "Naive Bayes")

# GÖREV 4: EĞİTİM VE DOĞRULAMA SETLERİ İÇİN ROC ANALİZİ
from sklearn.metrics import roc_curve, auc
from sklearn.preprocessing import label_binarize
import numpy as np
import matplotlib.pyplot as plt

# 1. Gerçek etiketleri bilgisayarın anlayacağı 0-1 formatına getiriyoruz
y_train_bin = label_binarize(y_train, classes=rf_model.classes_)
y_val_bin = label_binarize(y_val, classes=rf_model.classes_)

# 2. En başarılı model olan Random Forest'ın tahmin olasılık skorlarını alıyoruz
rf_score_train = rf_model.predict_proba(X_train)
rf_score_val = rf_model.predict_proba(X_val)

# 3. Eğitim Seti için Genel (Macro-average) ROC Değerlerini Hesaplama
fpr_train, tpr_train, _ = roc_curve(y_train_bin.ravel(), rf_score_train.ravel())
roc_auc_train = auc(fpr_train, tpr_train)

# 4. Doğrulama Seti için Genel (Macro-average) ROC Değerlerini Hesaplama
fpr_val, tpr_val, _ = roc_curve(y_val_bin.ravel(), rf_score_val.ravel())
roc_auc_val = auc(fpr_val, tpr_val)

# 5. Görselleştirme: İki Eğrinin Karşılaştırmalı Grafiği
plt.figure(figsize=(8, 6))
plt.plot(fpr_train, tpr_train, label=f'Eğitim Seti Genel ROC (AUC = {roc_auc_train:.4f})', color='blue', lw=2)
plt.plot(fpr_val, tpr_val, label=f'Doğrulama Seti Genel ROC (AUC = {roc_auc_val:.4f})', color='orange', lw=2)

plt.plot([0, 1], [0, 1], 'k--', lw=1.5)
plt.xlim([0.0, 1.0])
plt.ylim([0.0, 1.05])
plt.xlabel('Yanlış Pozitif Oranı (False Positive Rate)')
plt.ylabel('Doğru Pozitif Oranı (True Positive Rate)')
plt.title('Random Forest - Eğitim vs Doğrulama Seti Karşılaştırmalı ROC Eğrisi')
plt.legend(loc="lower right")
plt.grid(True, alpha=0.3)
plt.show()

# GÖREV 4: EĞİTİM VS DOĞRULAMA SETİ RECALL (DUYARLILIK) ANALİZİ
from sklearn.metrics import recall_score
import pandas as pd
import matplotlib.pyplot as plt

# 1. Tahminleri Eğitim ve Doğrulama (Validation) setleri için alıyoruz
y_train_pred = rf_model.predict(X_train)
